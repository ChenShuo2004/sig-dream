import { execFileSync } from "node:child_process";
import { mkdirSync, copyFileSync } from "node:fs";
import { resolve } from "node:path";
mkdirSync("release", { recursive: true });
const npmCli = process.env.npm_execpath;
const command = npmCli ? process.execPath : process.platform === "win32" ? "npm.cmd" : "npm";
const args = npmCli ? [npmCli] : [];
args.push("pack", "./packages/canvas-agent", "--pack-destination", "release", "--json");
const output = execFileSync(command, args, { encoding: "utf8", shell: process.platform === "win32" && !npmCli });
const [{ filename }] = JSON.parse(output);
copyFileSync(resolve("release", filename), resolve("release/canvas-agent.tgz"));
console.log(`Maintained Canvas Agent archive: release/${filename}`);
